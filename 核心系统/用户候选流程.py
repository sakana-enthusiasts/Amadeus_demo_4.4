"""核心阶段编排；通过获取器使用已有插件，产物属于本次运行。"""

from typing import Any

import pandas as pd


def 运行用户候选导入(数据管理器, 获取插件, 文件名, 文件内容, 字段映射, 用户筛选设置=None, 候选类型="通用候选", 应用配置=None) -> dict[str, Any]:
    设置 = dict(用户筛选设置 or {})
    配置编号 = str(应用配置 or 设置.get("应用配置") or "user_custom")
    设置["应用配置"] = 配置编号
    run_id = 数据管理器.创建运行(
        配置编号,
        文件名,
        {"候选类型": 候选类型, "规则启用覆盖": 设置.get("规则启用覆盖", {})},
    )
    上下文 = {
        "数据管理器": 数据管理器,
        "运行编号": run_id,
        "文件名": 文件名,
        "文件内容": 文件内容,
        "字段映射": 字段映射,
        "候选类型": 候选类型,
        "应用配置": 配置编号,
    }
    导入 = 获取插件("通用候选表导入").执行(上下文)
    身份 = 获取插件("化合物身份转换").执行({
        "数据管理器": 数据管理器,
        "身份输入标识": "用户导入_统一候选记录",
        "身份输出标识": "用户导入_化合物身份映射",
        "允许网络身份查询": bool(设置.get("允许网络身份查询", False)),
    })
    结构 = 获取插件("RDKit结构处理").执行({"数据管理器": 数据管理器, "用户结构处理": True})
    描述符 = 获取插件("RDKit普通描述符").执行({"数据管理器": 数据管理器, "用户描述符处理": True})
    HSP初筛 = 获取插件("用户候选HSP初筛").执行({"数据管理器": 数据管理器})
    筛选 = 获取插件("用户候选规则筛选").执行({
        "数据管理器": 数据管理器,
        "用户筛选设置": 设置,
        "候选输入标识": "用户导入_HSP初筛记录",
    })
    报告 = 获取插件("通用运行报告导出").执行({
        "数据管理器": 数据管理器,
        "运行编号": run_id,
        "应用配置": 配置编号,
    })
    return {
        "run_id": run_id,
        "应用配置": 配置编号,
        "导入记录数": len(导入),
        "身份已匹配数": int(身份["匹配状态"].astype(str).str.startswith("已匹配").sum()),
        "待人工确认数": int(身份["匹配状态"].eq("待人工确认").sum()),
        "结构成功数": int(结构["结构状态"].eq("已获得").sum()),
        "HSP已计算数": int(HSP初筛.get("与BA的HSP状态", pd.Series(dtype=str)).eq("已计算").sum()),
        "规则通过数": int(筛选["规则总状态"].eq("通过").sum()),
        "无法评估数": int(筛选["规则总状态"].eq("无法评估").sum()),
        "跳过规则数": int(筛选["规则总状态"].eq("跳过").sum()),
        "报告路径": str(报告),
    }

