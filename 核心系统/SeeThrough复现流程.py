"""核心阶段编排；通过获取器使用已有插件，产物属于本次运行。"""

from typing import Any

import pandas as pd
from 设置.插件启用设置 import 启用结果可视化


def 运行补充数据3复现(数据管理器, 获取插件) -> dict[str, Any]:
    run_id = 数据管理器.创建运行(运行类型="SeeThrough补充数据3", 输入来源="SeeThrough Supplementary Data 3")
    上下文 = {"数据管理器": 数据管理器}
    导入 = 获取插件("论文表格导入").执行(上下文)
    结构 = 获取插件("RDKit结构处理").执行(上下文)
    描述符 = 获取插件("RDKit普通描述符").执行(上下文)
    距离 = 获取插件("汉森距离计算").执行(上下文)
    合并 = 获取插件("化学属性合并").执行(上下文)
    return {
        "run_id": run_id,
        "导入候选数量": len(导入),
        "结构成功数量": int(结构["结构状态"].eq("已获得").sum()),
        "描述符成功数量": int(描述符.loc[描述符["是否计算成功"], "候选编号"].nunique()),
        "汉森距离记录数量": len(距离),
        "统一记录数量": len(合并),
    }


def 运行补充数据2复现(数据管理器, 获取插件, 启用网络查询=False) -> dict[str, Any]:
    """保留论文复现入口；最终10标签仅在合并后可选对照，不参与筛选。"""
    run_id = 数据管理器.创建运行(运行类型="SeeThrough补充数据2", 输入来源="SeeThrough Supplementary Data 2")
    上下文 = {"数据管理器": 数据管理器}
    导入 = 获取插件("补充数据2表格导入").执行(上下文)
    规则 = 获取插件("规则筛选")
    初筛 = 规则.执行数值初筛(上下文)
    身份 = 获取插件("化合物身份转换").执行({
        **上下文,
        "身份输入标识": "补充数据2_数值初筛记录",
        "身份输出标识": "补充数据2_41候选身份映射",
        "允许网络身份查询": 启用网络查询,
    })
    结构 = 获取插件("RDKit结构处理").执行({**上下文, "补充数据2结构处理": True, "允许网络结构查询": 启用网络查询})
    描述符 = 获取插件("RDKit普通描述符").执行({**上下文, "补充数据2描述符处理": True})
    距离 = 获取插件("补充数据2汉森距离计算").执行(上下文)
    自动 = 规则.执行最终自动规则筛选(上下文)
    合并 = 获取插件("补充数据2属性合并").执行(上下文)
    # 冲突对照使用本轮从论文原件导入的表3，不读取其他运行的中间结果。
    获取插件("论文表格导入").执行(上下文)
    冲突 = 获取插件("官方数据冲突检测").执行(上下文)
    PubChem证据 = 获取插件("PubChem查询").执行({**上下文, "启用网络毒性查询": 启用网络查询})
    CompTox状态 = 获取插件("CompTox接口状态").执行(上下文)
    毒性视图 = 获取插件("毒性证据视图").执行(上下文)
    动物模型 = 毒性视图["动物模式"]
    报告 = 获取插件("筛选报告导出").执行(上下文)
    图表 = (
        获取插件("筛选结果图表").执行(上下文)
        if 启用结果可视化()
        else {}
    )
    自动通过 = 自动["自动规则通过"].astype(str).str.lower().eq("true")
    最终标签 = 合并.get("论文最终10候选标签", pd.Series("", index=合并.index)).eq("是")
    return {
        "run_id": run_id,
        "清理后真实候选数": len(导入),
        "数值初筛通过数": int(初筛["数值初筛通过"].astype(str).str.lower().eq("true").sum()),
        "身份处理数": len(身份),
        "结构成功数": int(结构["结构状态"].eq("已获得").sum()),
        "描述符成功数": int(描述符.loc[描述符["是否计算成功"], "候选编号"].nunique()),
        "汉森距离记录数量": len(距离),
        "自动规则最终剩余数": int(自动通过.sum()),
        "论文最终10恢复数": int((自动通过 & 最终标签).sum()),
        "官方数据冲突数": len(冲突),
        "PubChem毒性证据数": len(PubChem证据),
        "CompTox状态数": len(CompTox状态),
        "动物模型记录数": len(动物模型),
        "报告路径": str(报告),
        "数量图PNG": str(图表["数量图PNG"]) if 图表 else "",
        "分布图PNG": str(图表["分布图PNG"]) if 图表 else "",
        "结果可视化已启用": 启用结果可视化(),
    }

