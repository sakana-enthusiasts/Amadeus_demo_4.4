def test_HSP核心不绑定论文或固定参照() -> None:
    距离 = HSP计算核心.计算距离({"HSP_dD": 18, "HSP_dP": 8, "HSP_dH": 7}, {"dD": 17, "dP": 7, "dH": 6})
    assert round(距离, 6) == round(6**0.5, 6)
    缺失 = HSP计算核心.评估({"HSP_dD": 18}, {"HSP_dD": 17, "HSP_dP": 7, "HSP_dH": 6})
    assert 缺失["HSP状态"] == "无法评估" and pd.isna(缺失["汉森距离_Ra"])


def test_颅骨用途评估保留缺失状态且可写入(tmp_path: Path) -> None:
    管理器 = 文件数据访问管理器(tmp_path)
    批次 = "batch_demo"
    确认清单 = pd.DataFrame([{
        "来源运行编号": "run_1", "候选编号": "C1", "化学名称": "候选A", "CAS": "1-1-1", "浓度值": 10, "浓度单位": "%",
    }])
    成分 = pd.DataFrame([{
        "成分键": "run_1::C1", "候选编号": "C1", "化学名称": "候选A", "CAS": "1-1-1", "浓度值": 10, "浓度单位": "%",
        "颅骨透明化角色": "RI匹配液", "纯物质RI": 1.6, "浓度下RI": 1.55, "实验水合评分": pd.NA,
        "HSP_dD": 18, "HSP_dP": 8, "HSP_dH": 7,
    }])
    保存成分证据(管理器, 批次, 成分)
    保存HSP参照(管理器, 批次, pd.DataFrame([{"参照体系": "AqIS", "HSP_dD": 17, "HSP_dP": 7, "HSP_dH": 6, "数据来源": "实验"}]))
    保存配方设置(管理器, 批次, {"混合液实测RI": "1.558", "实验混溶性": "均一", "稳定性状态": "稳定"})
    保存实验记录(管理器, 批次, pd.DataFrame([{"终点": "透射率", "数值": 80, "单位": "%", "数据来源": "实验"}]))
    结果 = 运行用途评估(管理器, 批次, 确认清单, 默认用途配置())
    assert 结果["HSP结果"].loc[0, "HSP状态"] == "已计算"
    assert 结果["配方摘要"].loc[0, "混合液RI与目标差值"] == -0.002
    assert 结果["成分评估"].loc[0, "水合数据状态"] == "待补实验水合评分"
    assert 结果["实验终点"].loc[0, "状态"] == "已记录"


def test_确认清单自动生成描述符并聚合多化合物(tmp_path: Path) -> None:
    管理器 = 运行数据管理器(tmp_path)
    run_id = 管理器.创建运行("user_custom", "two_components.csv")
    管理器.保存筛选结果("用户导入_规则筛选结果", pd.DataFrame([
        {"候选编号": "C1", "化学名称": "Ethanol", "CAS号": "64-17-5", "规则总状态": "通过"},
        {"候选编号": "C2", "化学名称": "Ethylene glycol", "CAS号": "107-21-1", "规则总状态": "通过"},
    ]))
    管理器.保存中间结果("用户导入_化合物身份映射", pd.DataFrame([
        {"候选编号": "C1", "Canonical SMILES": "CCO", "Isomeric SMILES": "CCO"},
        {"候选编号": "C2", "Canonical SMILES": "OCCO", "Isomeric SMILES": "OCCO"},
    ]))
    草稿元数据, 草稿 = 向工作草稿追加候选(管理器, run_id, ["C1", "C2"])
    草稿.loc[:, "浓度值"] = [20, 80]
    草稿.loc[:, "浓度单位"] = "%"
    草稿.loc[:, "颅骨透明化角色"] = ["RI匹配液", "共溶剂"]
    草稿.loc[:, "HSP_dD"] = [15.8, 16.8]
    草稿.loc[:, "HSP_dP"] = [8.8, 11.5]
    草稿.loc[:, "HSP_dH"] = [19.4, 26.0]
    保存工作草稿成分(管理器, 草稿元数据["草稿编号"], 草稿)
    批次, _ = 确认工作草稿(管理器, 草稿元数据["草稿编号"], "二组分颅骨配方", "颅骨透明化")
    全局 = 文件数据访问管理器(tmp_path)
    描述符 = 读取确认批次描述符(全局, 批次["批次编号"])
    特征 = 全局.读取软件数据库表格(配方特征标识)
    组分HSP = 全局.读取软件数据库表格(组分HSP结果标识)
    特征 = 特征.loc[特征["批次编号"].eq(批次["批次编号"])]
    组分HSP = 组分HSP.loc[组分HSP["批次编号"].eq(批次["批次编号"])]
    assert 描述符["是否计算成功"].astype(str).eq("True").all()
    assert str(特征.iloc[0]["描述符聚合状态"]).startswith("已按用户填写的百分比")
    assert len(组分HSP) == 2 and set(组分HSP["HSP状态"]) == {"已计算"}
