"""按证据保留物种、途径与终点差异，生成两种非打分式毒性视图。"""

from typing import Any

import pandas as pd

from 设置.毒性设置 import 当前动物实验给药途径, 当前动物实验物种, 当前动物实验暴露时长, 当前动物实验暴露模式, 当前主要关注终点
from 插件.插件接口 import 基础插件接口


class 毒性证据视图插件(基础插件接口):
    插件标识 = "毒性证据视图"

    @staticmethod
    def _字典() -> pd.DataFrame:
        return pd.DataFrame({"毒性终点": ["急性毒性", "重复给药", "细胞毒性", "肝毒性", "肾毒性", "神经毒性", "遗传毒性", "致癌性", "生殖发育毒性", "局部刺激和腐蚀", "致敏", "安全药理"], "说明": ["单次暴露", "重复暴露", "体外细胞", "肝脏相关", "肾脏相关", "神经系统", "遗传损伤", "致癌风险", "生殖和发育", "局部组织反应", "免疫致敏", "功能性安全药理"]})

    @staticmethod
    def _优先级() -> pd.DataFrame:
        return pd.DataFrame({"优先级": [1, 2, 3, 4, 5, 6], "证据条件": ["小鼠、相同给药途径、相近暴露时长", "大鼠、相同给药途径", "其他哺乳动物体内", "啮齿类体外", "人源体外和已知人类危害", "计算预测"], "物种是否匹配": ["是", "部分", "部分", "部分", "否", "否"], "给药途径是否匹配": ["是", "是", "视记录", "不适用", "不适用", "不适用"], "是否为实验数据": ["是", "是", "是", "是", "是/否", "否"], "是否能追溯原始来源": ["优先", "优先", "优先", "优先", "优先", "模型说明"]})

    def 执行(self, 数据上下文: dict[str, Any]) -> dict[str, pd.DataFrame]:
        数据管理器 = 数据上下文["数据管理器"]
        候选 = 数据管理器.读取筛选结果("补充数据2_规则筛选统一记录")
        候选 = 候选[候选["自动规则通过"].astype(str).str.lower().eq("true")].copy()
        GHS = 数据管理器.读取中间结果("PubChem_GHS毒性证据")
        CompTox = 数据管理器.读取中间结果("CompTox毒性查询状态")
        try:
            条件表 = 数据管理器.读取软件数据库表格("当前实验条件.csv")
            条件 = 条件表.iloc[0].to_dict() if not 条件表.empty else {}
        except FileNotFoundError:
            条件 = {}
        实验物种 = str(条件.get("当前实验物种", "") or 当前动物实验物种 or "")
        实验途径 = str(条件.get("当前给药途径", "") or 当前动物实验给药途径 or "")
        暴露时长 = str(条件.get("暴露时长", "") or 当前动物实验暴露时长 or "")
        暴露模式 = str(条件.get("暴露模式", "") or 当前动物实验暴露模式 or "")
        关注终点 = str(条件.get("主要关注终点", "") or 当前主要关注终点 or "")
        证据 = GHS.copy()
        if not CompTox.empty:
            证据["CompTox接口状态"] = 证据["候选编号"].map(CompTox.set_index("候选编号")["CompTox接口状态"])
        基准清单 = pd.DataFrame([{ "候选编号": "BA", "化学名称": "Benzyl Alcohol", "CAS": "100-51-6", "PubChem CID": "244"}, {"候选编号": "VA", "化学名称": "Veratryl Alcohol", "CAS": "93-03-8", "PubChem CID": "7118"}, {"候选编号": "ANP", "化学名称": "Antipyrine", "CAS": "60-80-0", "PubChem CID": "2206"}])
        基准清单["项目角色"] = "项目基准物"
        基准清单["身份转换状态"] = "已记录CAS和PubChem CID；可复用身份查询接口"
        基准清单["GHS查询状态"] = "尚未查询（当前GHS证据仅覆盖20个自动候选）"
        基准清单["CompTox接口状态"] = "未配置" if CompTox.empty else str(CompTox.iloc[0].get("CompTox接口状态", "未查询"))
        基准清单["动物实验匹配证据"] = "无已导入同条件实验记录"
        基准 = pd.concat([基准清单, pd.DataFrame([{ "候选编号": "当前配方其他成分", "化学名称": "未配置", "CAS": "", "项目角色": "待用户配置", "身份转换状态": "未配置", "GHS查询状态": "未查询", "CompTox接口状态": "未查询", "动物实验匹配证据": "未配置"}]), 候选[["候选编号", "论文_化学名称", "论文_CAS号"]].rename(columns={"论文_化学名称": "化学名称", "论文_CAS号": "CAS"}).assign(项目角色="自动数值候选", 身份转换状态="见41候选身份映射", GHS查询状态="见毒性原始证据", CompTox接口状态="见接口状态表", 动物实验匹配证据="尚无已导入同条件实验记录")], ignore_index=True)
        动物记录, 人体记录 = [], []
        for _, 行 in 候选.iterrows():
            该证据 = 证据[证据["候选编号"].eq(行["候选编号"])]
            小鼠 = 该证据[该证据["物种"].eq("小鼠")]
            大鼠 = 该证据[该证据["物种"].eq("大鼠")]
            实验 = 该证据[该证据["原始数据、数据库汇总或模型预测"].eq("原始数据")]
            分类 = "有相关毒性证据" if not 实验.empty else ("只有间接证据" if not 该证据.empty else "尚未查询")
            动物记录.append({"候选编号": 行["候选编号"], "化学名称": 行["论文_化学名称"], "当前动物实验物种": 实验物种 or "未配置（不作猜测）", "当前实验给药途径": 实验途径 or "未配置（不作猜测）", "暴露时长": 暴露时长 or "未配置", "暴露模式": 暴露模式 or "未配置", "主要关注终点": 关注终点 or "未配置", "是否有小鼠数据": "是" if not 小鼠.empty else "否", "是否有大鼠数据": "是" if not 大鼠.empty else "否", "给药途径": "；".join(该证据["给药途径"].dropna().unique()) or "数据不足", "是否与当前实验途径匹配": "未配置，无法判断" if not 实验途径 else "无匹配实验记录", "是否存在明显急性或器官毒性信号": "未检出可判定实验记录", "最高相关证据": 分类, "数据不足项": "小鼠同途径/近似时长的可追溯实验数据", "相对于BA、VA和ANP的比较": "三个基准物尚无同条件实验记录；当前仅可比较身份与GHS查询状态"})
            人体记录.append({"候选编号": 行["候选编号"], "化学名称": 行["论文_化学名称"], "已知人体危险记录": "未建立人体危险结论；见GHS提示", "人源体外数据": "数据不足", "人体代谢或药代信息": "接口未实现", "动物口服重复给药数据": "数据不足", "明显肝毒性、遗传毒性、生殖毒性等标记": "未检出可判定实验记录", "分子量": 行.get("分子量", ""), "代谢接口状态": "仅接口", "BBB接口状态": "仅接口", "人体转化信息是否不足": "是", "证据分类": 分类, "说明": "仅信息展示与缺口分析；不作人体安全结论。"})
        动物 = pd.DataFrame(动物记录); 人体 = pd.DataFrame(人体记录)
        数据管理器.保存筛选结果("毒性原始证据", 证据)
        数据管理器.保存筛选结果("项目基准物清单", 基准)
        数据管理器.保存筛选结果("毒性终点字典", self._字典())
        数据管理器.保存筛选结果("毒性证据相关性优先级表", self._优先级())
        数据管理器.保存筛选结果("当前动物实验模式结果", 动物)
        数据管理器.保存筛选结果("未来人体口服模式结果", 人体)
        return {"毒性证据": 证据, "项目基准物": 基准, "动物模式": 动物, "人体模式": 人体}
