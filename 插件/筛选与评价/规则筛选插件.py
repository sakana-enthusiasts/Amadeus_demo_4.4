"""按 SeeThrough 补充方法执行可审计的补充数据2规则筛选。"""

from typing import Any

import pandas as pd

from 设置.筛选规则设置 import 估算折射率下限, 汉森距离_BA上限, 水合评分下限, 规则来源
from 插件.插件接口 import 基础插件接口


class 规则筛选插件(基础插件接口):
    插件标识 = "规则筛选"
    输入标识 = "补充数据2_统一候选记录"
    数值初筛输出标识 = "补充数据2_数值初筛记录"
    汉森输入标识 = "补充数据2_汉森距离结果"
    输出标识 = "补充数据2_自动规则筛选记录"
    统计输出标识 = "补充数据2_规则筛选步骤统计"

    def 执行最终自动规则筛选(self, 数据上下文: dict[str, Any]) -> pd.DataFrame:
        """仅使用补充数据2数值字段与已计算距离；绝不读取论文最终10标签。"""
        数据管理器 = 数据上下文["数据管理器"]
        记录 = 数据管理器.读取中间结果(self.数值初筛输出标识).copy()
        距离 = 数据管理器.读取中间结果(self.汉森输入标识).copy()
        距离["汉森距离_Ra"] = pd.to_numeric(距离["汉森距离_Ra"], errors="coerce")
        透视 = 距离.pivot(index="候选编号", columns="参照试剂编号", values="汉森距离_Ra").reset_index().rename(columns={"BA": "汉森距离_与BA", "VA": "汉森距离_与VA"})
        记录 = 记录.merge(透视, on="候选编号", how="left", validate="one_to_one")
        数值初筛通过 = 记录["数值初筛通过"].astype(str).str.lower().eq("true")
        BA距离通过 = 记录["汉森距离_与BA"] < 汉森距离_BA上限
        记录["规则_汉森距离与BA小于10"] = self._状态(BA距离通过, 数值初筛通过)
        记录["自动规则通过"] = 数值初筛通过 & BA距离通过
        记录.loc[数值初筛通过 & ~BA距离通过, "自动排除原因"] = f"与BA的Hansen距离未小于 {汉森距离_BA上限}"
        记录.loc[记录["自动规则通过"], "自动排除原因"] = "自动数值规则通过"
        完整 = 记录["规则_必要字段完整"].eq("通过")
        水合下限 = 完整 & 记录["规则_水合评分不低于负1点5"].eq("通过")
        高于BA = 水合下限 & 记录["规则_水合能力高于BA"].eq("通过")
        eRI = 高于BA & 记录["规则_eRI大于1点58"].eq("通过")
        统计 = pd.DataFrame([
            self._统计行("必要字段完整", len(记录), int(完整.sum()), "水合能力、eRI、dD/dP/dH均为数值", "数据可用性要求"),
            self._统计行("水合评分不低于-1.5", int(完整.sum()), int(水合下限.sum()), f"水合评分 >= {水合评分下限}", 规则来源["水合评分下限"]),
            self._统计行("水合能力高于BA", int(水合下限.sum()), int(高于BA.sum()), f"> BA = {float(记录['BA水合能力阈值'].iloc[0]):.6f}", 规则来源["水合能力高于BA"]),
            self._统计行("eRI大于1.58", int(高于BA.sum()), int(eRI.sum()), f"eRI > {估算折射率下限}", 规则来源["估算折射率"]),
            self._统计行("与BA的Hansen距离小于10", int(eRI.sum()), int(记录["自动规则通过"].sum()), f"Ra(BA) < {汉森距离_BA上限}", 规则来源["汉森距离"]),
        ])
        数据管理器.保存中间结果(self.输出标识, 记录)
        数据管理器.保存中间结果(self.统计输出标识, 统计)
        return 记录

    @staticmethod
    def _状态(掩码: pd.Series, 可评估: pd.Series) -> pd.Series:
        return pd.Series("未评估", index=掩码.index).mask(可评估 & 掩码, "通过").mask(可评估 & ~掩码, "排除")

    @staticmethod
    def _统计行(步骤: str, 输入数: int, 剩余数: int, 阈值: str, 来源: str) -> dict[str, Any]:
        return {"筛选步骤": 步骤, "筛选前数量": 输入数, "排除数量": 输入数 - 剩余数, "剩余数量": 剩余数, "阈值或条件": 阈值, "论文来源": 来源}

    def 执行数值初筛(self, 数据上下文: dict[str, Any]) -> pd.DataFrame:
        数据管理器 = 数据上下文["数据管理器"]
        记录 = 数据管理器.读取中间结果(self.输入标识).copy()
        for 字段 in ["论文_水合能力平均值", "论文_水合能力标准差", "论文_eRI", "论文_pH", "论文_dD", "论文_dP", "论文_dH"]:
            记录[字段] = pd.to_numeric(记录[字段], errors="coerce")
        必要字段 = ["论文_水合能力平均值", "论文_eRI", "论文_dD", "论文_dP", "论文_dH"]
        字段完整 = 记录[必要字段].notna().all(axis=1)
        水合下限通过 = 记录["论文_水合能力平均值"] >= 水合评分下限
        BA行 = 记录.loc[记录["论文_CAS号"].eq("100-51-6")]
        if len(BA行) != 1:
            raise ValueError("补充数据2中未唯一定位苄醇（CAS 100-51-6），无法建立水合阈值。")
        BA水合能力 = float(BA行.iloc[0]["论文_水合能力平均值"])
        前级一 = 字段完整 & 水合下限通过
        高于BA = 记录["论文_水合能力平均值"] > BA水合能力
        前级二 = 前级一 & 高于BA
        eRI通过 = 记录["论文_eRI"] > 估算折射率下限
        数值初筛通过 = 前级二 & eRI通过

        记录["规则_必要字段完整"] = self._状态(字段完整, pd.Series(True, index=记录.index))
        记录["规则_水合评分不低于负1点5"] = self._状态(水合下限通过, 字段完整)
        记录["规则_水合能力高于BA"] = self._状态(高于BA, 前级一)
        记录["规则_eRI大于1点58"] = self._状态(eRI通过, 前级二)
        记录["BA水合能力阈值"] = BA水合能力
        记录["数值初筛通过"] = 数值初筛通过
        记录["自动排除原因"] = ""
        记录.loc[~字段完整, "自动排除原因"] = "必要字段缺失或非数值"
        记录.loc[字段完整 & ~水合下限通过, "自动排除原因"] = f"水合评分低于 {水合评分下限}"
        记录.loc[前级一 & ~高于BA, "自动排除原因"] = f"水合能力未高于BA（{BA水合能力:.6f}）"
        记录.loc[前级二 & ~eRI通过, "自动排除原因"] = f"eRI未大于 {估算折射率下限}"
        数据管理器.保存中间结果(self.数值初筛输出标识, 记录)
        return 记录

    def 执行最终规则筛选(self, 数据上下文: dict[str, Any]) -> pd.DataFrame:
        """旧调用名的安全兼容入口：只执行不含答案标签的自动规则。"""
        return self.执行最终自动规则筛选(数据上下文)

    def 执行(self, 数据上下文: dict[str, Any]) -> pd.DataFrame:
        """兼容插件接口；实际执行的自动规则从不读取论文最终10标签。"""
        return self.执行最终自动规则筛选(数据上下文)
