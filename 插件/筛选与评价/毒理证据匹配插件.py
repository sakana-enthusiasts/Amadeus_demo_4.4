"""本地毒理证据的可解释匹配插件。"""

from __future__ import annotations

from typing import Any

import pandas as pd

from 核心系统.毒理分析 import 毒理证据匹配引擎, 公开数据源接口状态, 规范化会话
from 插件.插件接口 import 基础插件接口


class 毒理证据匹配插件(基础插件接口):
    插件标识 = "毒理证据匹配"

    def 执行(self, 数据上下文: dict[str, Any]) -> dict[str, pd.DataFrame]:
        数据管理器 = 数据上下文["数据管理器"]
        会话 = 规范化会话(数据上下文.get("毒理会话"))
        证据 = 数据上下文.get("毒理证据")
        if not isinstance(证据, pd.DataFrame):
            本地表 = []
            try:
                本地表.append(数据管理器.读取筛选结果("毒理人工证据"))
            except FileNotFoundError:
                pass
            try:
                本地表.append(数据管理器.读取筛选结果("毒理历史证据"))
            except FileNotFoundError:
                pass
            证据 = pd.concat(本地表, ignore_index=True) if 本地表 else pd.DataFrame()
        if "证据可参与条件匹配" in 证据:
            可匹配掩码 = 证据["证据可参与条件匹配"].fillna(True).astype(str).str.casefold().isin({"true", "1", "是"})
            危险提示 = 证据[~可匹配掩码].copy()
            可匹配证据 = 证据[可匹配掩码].copy()
        else:
            危险提示, 可匹配证据 = pd.DataFrame(), 证据
        引擎 = 毒理证据匹配引擎(会话)
        匹配结果, 数据缺口 = 引擎.匹配(可匹配证据, 会话["化合物清单"])
        批次 = dict(会话.get("化合物批次") or {})
        for 表格 in (匹配结果, 数据缺口):
            if not 表格.empty:
                # 公开提示记录本身也带批次列；匹配输出统一以当前会话快照为准。
                表格["化合物批次编号"] = str(批次.get("批次编号", "未选择确认清单"))
                表格["来源运行编号"] = str(批次.get("来源运行编号", ""))
                表格["确认清单标识"] = str(批次.get("确认清单标识", ""))
        来源状态 = 公开数据源接口状态(会话["来源策略"])
        摘要 = pd.DataFrame([{
            "来源预设": 会话["来源策略"]["来源预设"],
            "化合物批次编号": str(批次.get("批次编号", "未选择确认清单")),
            "来源运行编号": str(批次.get("来源运行编号", "")),
            "确认清单标识": str(批次.get("确认清单标识", "")),
            "公开库查询": "已启用 PubChem GHS" if "PubChem GHS" in set(会话["来源策略"].get("启用公开数据源") or []) else "不查询",
            "本地或人工证据数": len(可匹配证据), "公开危险提示数": len(危险提示), "匹配记录数": len(匹配结果), "数据缺口数": len(数据缺口),
        }])
        数据管理器.保存筛选结果("毒理匹配结果", 匹配结果)
        数据管理器.保存筛选结果("毒理危险提示", 危险提示)
        数据管理器.保存筛选结果("毒理数据缺口", 数据缺口)
        数据管理器.保存筛选结果("毒理来源接口状态", 来源状态)
        数据管理器.保存筛选结果("毒理分析摘要", 摘要)
        return {"匹配结果": 匹配结果, "危险提示": 危险提示, "数据缺口": 数据缺口, "来源接口状态": 来源状态, "摘要": 摘要}
