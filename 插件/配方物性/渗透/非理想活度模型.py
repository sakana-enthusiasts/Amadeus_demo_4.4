from .接口 import 渗透压模型接口
from .理想渗透压 import 理想压力
from ..配方物性接口 import 有限数


class 渗透系数修正模型(渗透压模型接口):
    方法 = "osmotic_coefficient"
    自动优先级 = 10
    适用范围 = "用户提供当前配方和温度的有效渗透系数；不自动拟合活度"

    def 预测(self, 配方, 上游):
        系数 = 有限数(配方.参数.get(self.方法, {}).get("渗透系数"), "渗透系数", 严格正=True)
        return self.结果(理想压力(配方) * 系数, 警告=("渗透系数须适用于当前配方、温度及所用解离因子约定",))
