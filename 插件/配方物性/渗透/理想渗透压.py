from .接口 import 渗透压模型接口
from ..配方物性接口 import 有限数, 输入不可用


def 理想压力(配方):
    if not 配方.成分:
        raise 输入不可用("配方无成分")
    总浓度 = 0.0
    for 行 in 配方.成分:
        角色 = 行.get("渗透角色")
        if 角色 == "溶剂":
            continue
        if 角色 != "溶质":
            raise 输入不可用("每个成分须明确填写渗透角色：溶剂或溶质")
        c = 有限数(行.get("摩尔浓度_mol_L"), "摩尔浓度_mol_L", 最小=0)
        if c > 0:
            总浓度 += c * 有限数(行.get("范特霍夫因子"), "范特霍夫因子", 严格正=True)
    return 8.31446261815324 * 配方.温度K() * 总浓度 * 1000


class 理想渗透压模型(渗透压模型接口):
    方法 = "ideal_osmotic"
    适用范围 = "理想稀溶液；使用配方最终体积下的溶质摩尔浓度和显式范特霍夫因子"

    def 预测(self, 配方, 上游):
        return self.结果(理想压力(配方), 警告=("仅用于快速初筛；高浓度非理想体系需实测或活度修正；不等于脱水程度",))
